"""DB tests for the ScrapeRun recorder (B18, scraper side)."""

from __future__ import annotations

from datetime import date, datetime

import pytest
from sqlalchemy import text

from scraper import scrape_run


def _runs(db) -> list[dict]:
    with db.connect() as c:
        rows = c.execute(text('SELECT * FROM "ScrapeRun" ORDER BY "startedAt"')).mappings().all()
    return [dict(r) for r in rows]


def test_start_run_inserts_a_running_row_with_a_database_generated_id(db) -> None:
    run_id = scrape_run.start_run("hemnet", "ostermalm")
    assert run_id
    (row,) = _runs(db)
    assert row["id"] == run_id and len(run_id) == 36  # uuid text generated by Postgres
    assert (row["source"], row["district"], row["status"]) == ("hemnet", "ostermalm", "running")
    assert (row["pages"], row["rowsUpserted"], row["rowsRejected"]) == (0, 0, 0)
    assert row["finishedAt"] is None and row["error"] is None and row["oldestSoldAt"] is None
    assert isinstance(row["startedAt"], datetime)


def test_bump_updates_counters_while_the_run_stays_running(db) -> None:
    run_id = scrape_run.start_run("booli", "vasastan")
    scrape_run.bump(run_id, pages=3, rows_upserted=100, rows_rejected=4, oldest_sold_at=date(2026, 4, 1))
    (row,) = _runs(db)
    assert (row["status"], row["pages"], row["rowsUpserted"], row["rowsRejected"]) == ("running", 3, 100, 4)
    assert row["oldestSoldAt"] == date(2026, 4, 1) and row["finishedAt"] is None


@pytest.mark.parametrize("status", ["ok", "partial", "failed"])
def test_finish_run_closes_the_row(db, status) -> None:
    run_id = scrape_run.start_run("hemnet", "sodermalm")
    scrape_run.finish_run(
        run_id, status, pages=5, rows_upserted=170, rows_rejected=2, oldest_sold_at=date(2026, 3, 1),
        error=None if status == "ok" else "page 5 failed",
    )
    (row,) = _runs(db)
    assert row["status"] == status and row["finishedAt"] is not None
    assert (row["pages"], row["rowsUpserted"], row["rowsRejected"]) == (5, 170, 2)
    assert row["error"] == (None if status == "ok" else "page 5 failed")
    assert row["oldestSoldAt"] == date(2026, 3, 1)


def test_finish_run_rejects_an_unknown_status(db) -> None:
    run_id = scrape_run.start_run("hemnet", "norrmalm")
    with pytest.raises(ValueError):
        scrape_run.finish_run(run_id, "running", pages=0, rows_upserted=0, rows_rejected=0, oldest_sold_at=None)


def test_each_invocation_gets_its_own_row(db) -> None:
    a = scrape_run.start_run("hemnet", "ostermalm")
    b = scrape_run.start_run("hemnet", "ostermalm")
    assert a != b and len(_runs(db)) == 2


def test_recorder_failures_never_raise_and_are_logged(db, monkeypatch, caplog) -> None:
    """A broken ScrapeRun table must not fail a crawl."""

    def boom(name):
        raise RuntimeError("no such table")

    monkeypatch.setattr(scrape_run, "table", boom)
    assert scrape_run.start_run("hemnet", "ostermalm") is None
    scrape_run.bump(None, pages=1, rows_upserted=1, rows_rejected=0, oldest_sold_at=None)  # no-ops
    scrape_run.finish_run(None, "ok", pages=1, rows_upserted=1, rows_rejected=0, oldest_sold_at=None)
    assert any("scrape run" in r.getMessage() and r.levelname == "WARNING" for r in caplog.records)


def test_a_new_run_marks_stale_running_rows_as_interrupted(db) -> None:
    """Commands hold the single-instance lock, so a row still `running` at start belongs
    to a process that died (Ctrl-C, SIGKILL, power loss)."""
    stale_a = scrape_run.start_run("hemnet", "ostermalm")
    stale_b = scrape_run.start_run("booli", "vasastan")  # also closes stale_a
    done = scrape_run.start_run("hemnet", "norrmalm")
    scrape_run.finish_run(done, "ok", pages=1, rows_upserted=1, rows_rejected=0, oldest_sold_at=None)
    fresh = scrape_run.start_run("hemnet", "sodermalm")
    by_id = {r["id"]: r for r in _runs(db)}
    for stale in (stale_a, stale_b):
        assert by_id[stale]["status"] == "failed" and by_id[stale]["error"] == "interrupted"
        assert by_id[stale]["finishedAt"] is not None
    assert by_id[done]["status"] == "ok" and by_id[done]["error"] is None  # finished rows are untouched
    assert by_id[fresh]["status"] == "running"  # the new run itself


def test_start_run_still_records_the_run_when_closing_stale_rows_fails(db, monkeypatch, caplog) -> None:
    def boom(session_, t):
        # a real database error: it would abort the whole transaction without a savepoint
        session_.execute(text("SELECT 1/0"))

    monkeypatch.setattr(scrape_run, "_close_stale", boom)
    run_id = scrape_run.start_run("hemnet", "ostermalm")
    assert run_id is not None
    assert [r["id"] for r in _runs(db)] == [run_id]
    assert any("stale" in r.getMessage() and r.levelname == "WARNING" for r in caplog.records)
