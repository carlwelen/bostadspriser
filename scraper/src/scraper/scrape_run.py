"""ScrapeRun bookkeeping: one row per `scrape`/`update`/`backfill` invocation for a
(source, district), so the web app can show how fresh the data is and so
coverage is observable. Prisma owns the table (status enum
running|ok|partial|failed, id generated by the database).

Legacy recording remains best-effort. Explicit crawl kinds carry essential state;
commands require successful start, checkpoint and finish writes.
"""

from __future__ import annotations

import logging
from datetime import date

from sqlalchemy import func, insert, or_, select, update

from .db import session, table

log = logging.getLogger("scraper.scrape_run")

FINAL_STATUSES = ("ok", "partial", "failed")


def _close_stale(s, t) -> None:
    """Mark every still-`running` row as interrupted.

    scrape/update/backfill hold the single-instance lock while they run, so a row
    that is still `running` when a new run starts belongs to a process that died
    (Ctrl-C, SIGKILL, power loss) before it could close its row.

    The assumption is only as wide as the lock: it is per *state directory and
    host* (SCRAPER_STORAGE_STATE). Two hosts, or two state directories, sharing one
    database would mark each other's live rows interrupted. (The row has no
    pid/host column and the schema is owned elsewhere, so nothing finer is recorded.)
    """
    s.execute(
        update(t)
        .where(t.c.status == "running")
        .values(status="failed", finishedAt=func.now(), error="interrupted")
    )


def start_run(
    source: str, district: str, *, kind: str = "legacy", since: date | None = None,
    last_page: int = 0, oldest_sold_at: date | None = None,
) -> str | None:
    """Close stale `running` rows (see _close_stale), then insert a new `running`
    row; returns its id, or None if recording failed."""
    try:
        t = table("ScrapeRun")
        with session() as s:
            try:
                # A savepoint: if closing stale rows fails, only that statement rolls
                # back and the new run is still recorded.
                with s.begin_nested():
                    _close_stale(s, t)
            except Exception as e:  # noqa: BLE001
                log.warning("could not close stale running rows error=%r", e)
                if kind != "legacy":
                    raise
            run_id = s.execute(
                insert(t).values(source=source, district=district, status="running", kind=kind,
                                 since=since, lastPage=last_page, oldestSoldAt=oldest_sold_at).returning(t.c.id)
            ).scalar_one()
            s.commit()
        return run_id
    except Exception as e:  # noqa: BLE001
        log.warning("scrape run not recorded source=%s district=%s error=%r", source, district, e)
        if kind != "legacy":
            raise
        return None


def bump(
    run_id: str | None,
    *,
    pages: int,
    rows_upserted: int,
    rows_rejected: int,
    oldest_sold_at: date | None,
    last_page: int = 0,
    required: bool = False,
) -> None:
    """Update the counters of a still-running row."""
    _update(
        run_id,
        required=required,
        lastPage=last_page,
        pages=pages,
        rowsUpserted=rows_upserted,
        rowsRejected=rows_rejected,
        oldestSoldAt=oldest_sold_at,
    )


def finish_run(
    run_id: str | None,
    status: str,
    *,
    pages: int,
    rows_upserted: int,
    rows_rejected: int,
    oldest_sold_at: date | None,
    error: str | None = None,
    last_page: int = 0,
    complete_through: date | None = None,
    required: bool = False,
) -> None:
    """Close the row with its final status (ok, partial or failed)."""
    if status not in FINAL_STATUSES:
        raise ValueError(f"final status must be one of {FINAL_STATUSES}, not {status!r}")
    _update(
        run_id,
        required=required,
        lastPage=last_page,
        completeThrough=complete_through,
        status=status,
        finishedAt=func.now(),
        pages=pages,
        rowsUpserted=rows_upserted,
        rowsRejected=rows_rejected,
        oldestSoldAt=oldest_sold_at,
        error=error,
    )


def _update(run_id: str | None, *, required: bool = False, **values) -> None:
    if run_id is None:
        if required:
            raise RuntimeError("durable run has no id")
        return
    try:
        t = table("ScrapeRun")
        with session() as s:
            result = s.execute(update(t).where(t.c.id == run_id).values(**values))
            if required and result.rowcount != 1:
                raise RuntimeError("durable run no longer exists")
            s.commit()
    except Exception as e:  # noqa: BLE001
        log.warning("scrape run %s not updated error=%r", run_id, e)
        if required:
            raise


def latest_run(
    source: str, district: str, *, kind: str, watermark: bool = False, not_after: date | None = None,
) -> dict | None:
    """Latest explicitly classified run; legacy rows never imply crawl coverage."""
    t = table("ScrapeRun")
    query = select(t).where(t.c.source == source, t.c.district == district, t.c.kind == kind)
    if not_after is not None:
        # Ignore corrupt future state while retaining earlier valid coverage.
        query = query.where(or_(t.c.since.is_(None), t.c.since <= not_after))
        if watermark:
            query = query.where(t.c.completeThrough <= not_after)
    if watermark:
        query = query.where(t.c.status == "ok", t.c.finishedAt.is_not(None), t.c.completeThrough.is_not(None))
    with session() as s:
        row = s.execute(query.order_by(t.c.startedAt.desc(), t.c.id.desc()).limit(1)).mappings().first()
    return dict(row) if row else None
