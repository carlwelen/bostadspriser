"""ScrapeRun bookkeeping: one row per `scrape`/`update`/`backfill` invocation for a
(source, district), so the web app can show how fresh the data is and so
coverage is observable. Prisma owns the table (status enum
running|ok|partial|failed, id generated by the database).

Recording is best-effort: a failure here is logged and never fails a crawl.
"""

from __future__ import annotations

import logging
from datetime import date

from sqlalchemy import func, insert, update

from .db import session, table

log = logging.getLogger("scraper.scrape_run")

FINAL_STATUSES = ("ok", "partial", "failed")


def _close_stale(s, t) -> None:
    """Mark every still-`running` row as interrupted.

    scrape/update/backfill hold the single-instance lock while they run, so a row
    that is still `running` when a new run starts belongs to a process that died
    (Ctrl-C, SIGKILL, power loss) before it could close its row.

    The assumption is only as wide as the lock: it is per *state directory and
    host* (SCRAPER_STORAGE_STATE). Two hosts, or two state directories, sharing one
    database would mark each other's live rows interrupted. (The row has no
    pid/host column and the schema is owned elsewhere, so nothing finer is recorded.)
    """
    s.execute(
        update(t)
        .where(t.c.status == "running")
        .values(status="failed", finishedAt=func.now(), error="interrupted")
    )


def start_run(source: str, district: str) -> str | None:
    """Close stale `running` rows (see _close_stale), then insert a new `running`
    row; returns its id, or None if recording failed."""
    try:
        t = table("ScrapeRun")
        with session() as s:
            try:
                # A savepoint: if closing stale rows fails, only that statement rolls
                # back and the new run is still recorded.
                with s.begin_nested():
                    _close_stale(s, t)
            except Exception as e:  # noqa: BLE001
                log.warning("could not close stale running rows error=%r", e)
            run_id = s.execute(
                insert(t).values(source=source, district=district, status="running").returning(t.c.id)
            ).scalar_one()
            s.commit()
        return run_id
    except Exception as e:  # noqa: BLE001
        log.warning("scrape run not recorded source=%s district=%s error=%r", source, district, e)
        return None


def bump(
    run_id: str | None,
    *,
    pages: int,
    rows_upserted: int,
    rows_rejected: int,
    oldest_sold_at: date | None,
) -> None:
    """Update the counters of a still-running row."""
    _update(
        run_id,
        pages=pages,
        rowsUpserted=rows_upserted,
        rowsRejected=rows_rejected,
        oldestSoldAt=oldest_sold_at,
    )


def finish_run(
    run_id: str | None,
    status: str,
    *,
    pages: int,
    rows_upserted: int,
    rows_rejected: int,
    oldest_sold_at: date | None,
    error: str | None = None,
) -> None:
    """Close the row with its final status (ok, partial or failed)."""
    if status not in FINAL_STATUSES:
        raise ValueError(f"final status must be one of {FINAL_STATUSES}, not {status!r}")
    _update(
        run_id,
        status=status,
        finishedAt=func.now(),
        pages=pages,
        rowsUpserted=rows_upserted,
        rowsRejected=rows_rejected,
        oldestSoldAt=oldest_sold_at,
        error=error,
    )


def _update(run_id: str | None, **values) -> None:
    if run_id is None:
        return
    try:
        t = table("ScrapeRun")
        with session() as s:
            s.execute(update(t).where(t.c.id == run_id).values(**values))
            s.commit()
    except Exception as e:  # noqa: BLE001
        log.warning("scrape run %s not updated error=%r", run_id, e)
